"""
Core Schemas for Autonomous SOC (Agentic-SOC)
Defines Pydantic models for telemetry ingestion, threat assessments, and SOAR actions.
"""

from typing import List, Optional, Dict, Any
from datetime import datetime
from pydantic import BaseModel, Field


class GeoLocation(BaseModel):
    """Geographic location information associated with telemetry IP."""
    city: str = Field(..., description="City name (e.g. London, New York)")
    country: str = Field(..., description="ISO Country Code or name (e.g. UK, USA)")
    lat: float = Field(..., description="Latitude (-90.0 to 90.0)")
    lon: float = Field(..., description="Longitude (-180.0 to 180.0)")


class TelemetryEvent(BaseModel):
    """Raw enterprise authentication telemetry event payload."""
    event_id: str = Field(..., description="Unique event identification string (UUID/hash)")
    timestamp: str = Field(..., description="ISO 8601 timestamp string")
    user_principal_name: str = Field(..., description="User UPN/Email (e.g. alex.hunter@enterprise.com)")
    source_ip: str = Field(..., description="IPv4 or IPv6 source address")
    session_token: str = Field(..., description="Authentication session token / bearer cookie")
    geo: GeoLocation = Field(..., description="Geographic location of source IP")
    user_agent: str = Field(..., description="HTTP User-Agent string")


class AgentAssessment(BaseModel):
    """Stateful assessment output generated by the LangGraph Multi-Agent Swarm."""
    event_id: str = Field(..., description="Correlated event ID")
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat() + "Z")
    user_principal_name: str
    source_ip: str
    classification: str = Field(..., description="Threat classification (e.g. AiTM Phishing, Token Theft, ATO, Benign)")
    mitre_technique: str = Field(..., description="MITRE ATT&CK ID & Technique (e.g. T1539 - Adversary-in-the-Middle)")
    risk_score: float = Field(..., description="Calculated algorithmic risk score (0 - 100)")
    indicators: List[str] = Field(default_factory=list, description="Extracted telemetry indicators and mathematically derived anomalies")
    action: str = Field(..., description="Triage action: AUTONOMOUS_CRITICAL_BLOCK | HUMAN_IN_LOOP_REQUIRED | AUTONOMOUS_MONITOR")
    reasoning: str = Field(..., description="Detailed analytical justification generated by swarm nodes")
    soar_execution_logs: List[Dict[str, Any]] = Field(default_factory=list, description="Automated SOAR mitigation execution trace")
    velocity_kmh: Optional[float] = Field(None, description="Calculated travel velocity in km/h if previous telemetry exists")
    token_entropy: Optional[float] = Field(None, description="Calculated Shannon entropy of session token")


class HITLApprovalRequest(BaseModel):
    """Payload to approve a paused Human-in-the-Loop mitigation action."""
    event_id: Optional[str] = None
    analyst_id: str = "analyst_secops_01"
    notes: Optional[str] = "Approved after manual SOC investigation."


class AuditLedgerResponse(BaseModel):
    """Response wrapper for immutable audit ledger logs."""
    total_count: int
    assessments: List[AgentAssessment]
